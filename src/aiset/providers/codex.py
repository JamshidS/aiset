"""Native Codex agent files, with hash-based protection for user edits.

Only Aiset's own flat TOML schema is written. Arbitrary user TOML is never parsed
and reserialized; this also keeps the generator compatible with Python 3.9.
"""
import hashlib
import json
import os
import re
import sys

from ..atomic import write_text_atomic

START = "<!-- aiset:codex:start -->"
END = "<!-- aiset:codex:end -->"
MANIFEST = ".codex/aiset/generated.json"
REASONING = ("", "minimal", "low", "medium", "high", "xhigh", "max", "ultra")
MODEL = re.compile(r"^[a-zA-Z0-9][a-zA-Z0-9._/-]{0,127}$")
CLAUDE_MODELS = {"inherit", "opus", "sonnet", "haiku", "fable"}
TEMPLATES = os.path.join(os.path.dirname(os.path.dirname(__file__)), "templates")


def digest(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def agent_name(member_id):
    """Keep Aiset roles away from native reserved names, including root.

    A suffix distinguishes ids whose punctuation/Unicode needs normalization.
    The roster ids and memory filenames themselves are unchanged.
    """
    normalized = re.sub(r"[^a-zA-Z0-9_]", "_", member_id)
    suffix = "_" + digest(member_id)[:8] if normalized != member_id else ""
    return "aiset_" + normalized + suffix


def safe_path(ws, relative):
    base = os.path.realpath(ws)
    path = os.path.join(base, *relative.split("/"))
    if os.path.commonpath((base, os.path.realpath(path))) != base:
        raise ValueError(f"Codex output leaves the workspace: {relative}")
    return path


def read(path):
    try:
        with open(path, encoding="utf-8", newline="") as f:
            return f.read()
    except FileNotFoundError:
        return None


def manifest(ws):
    text = read(safe_path(ws, MANIFEST))
    data = json.loads(text) if text is not None else {"version": 1, "files": {}}
    if not isinstance(data, dict) or data.get("version") != 1 or not isinstance(data.get("files"), dict):
        raise ValueError("invalid Codex generation manifest; restore .codex/aiset/generated.json before retrying")
    return data


def options(member):
    settings = member.get("codex", {})
    if not isinstance(settings, dict):
        raise ValueError(f"{member['id']}: codex settings must be an object")
    model = settings.get("model", "")
    effort = settings.get("reasoning", "")
    if not isinstance(model, str) or (model and (not MODEL.fullmatch(model) or model in CLAUDE_MODELS)):
        raise ValueError(f"{member['id']}: choose a Codex model id, or leave it empty to inherit")
    if effort not in REASONING:
        raise ValueError(f"{member['id']}: unsupported reasoning effort {effort!r}")
    return model, effort


def quoted(text):
    """A TOML basic string, including C0 controls, DEL and Unicode."""
    return json.dumps(str(text), ensure_ascii=False).replace("\u007f", "\\u007f")


def agent_toml(member, instructions):
    model, effort = options(member)
    fields = [("name", agent_name(member["id"])), ("description", f"{member['name']} - {member['role']}: {member.get('duty', '')}")]
    if model:
        fields.append(("model", model))
    if effort:
        fields.append(("model_reasoning_effort", effort))
    fields.append(("developer_instructions", instructions))
    return "# Generated by aiset. Reinitialization preserves edits.\n" + "".join(f"{key} = {quoted(value)}\n" for key, value in fields)


def render(template, values):
    with open(os.path.join(TEMPLATES, template), encoding="utf-8") as f:
        text = f.read()
    for key, value in values.items():
        text = text.replace("{{" + key + "}}", str(value))
    if re.search(r"\{\{\w+\}\}", text):
        raise ValueError(f"unresolved Codex template field in {template}")
    return text.rstrip() + "\n"


def instructions(ws, roster, repos):
    from ..workspace import script_command
    ws = os.path.abspath(ws).replace("\\", "/")
    team = ws + "/.claude/team"
    base = {
        "WS": ws, "TEAM_NAME": roster["team"], "ROSTER": team + "/roster.json",
        "KNOWLEDGE": team + "/knowledge", "BOARDS": team + "/tasks", "EPISODES": team + "/episodes",
        "TEAMMAP": script_command("teammap", sys.executable),
        "TEAM_TABLE": "\n".join(f"| `{agent_name(m['id'])}` | {m['name']} | {m['role']} | {', '.join(m.get('repos') or []) or m.get('duty', '')} |"
                                for m in roster["members"]),
        "INTEGRATION_AGENT": agent_name("integration-checker"),
        "PINNED_MODELS": "\n".join(
            f"- `{agent_name(m['id'])}`: " + ", ".join(
                f"{key}={value}" for key, value in zip(("model", "reasoning"), options(m)) if value)
            for m in roster["members"] if any(options(m))),
        "TEST_TABLE": "\n".join(f"- `{r['name']}`: " + (", ".join(f"`{c}`" for c in r["checks"]) or "look up the repository's check commands") for r in repos),
    }
    if not any(m.get("id") == "pm" for m in roster.get("members", [])):
        raise ValueError("the Codex roster needs a PM member")
    out = {}
    for member in roster["members"]:
        member_id = member["id"]
        if not isinstance(member_id, str) or member_id in (".", "..") or not re.fullmatch(r"[\w.-]+", member_id):
            raise ValueError(f"invalid Codex agent id {member_id!r}; use letters, numbers, underscores, dots or hyphens")
        options(member)
        values = {**base, "ID": member_id, "NATIVE_AGENT": agent_name(member_id), "NAME": member["name"], "ROLE": member["role"],
                  "DUTY": member.get("duty", ""), "REPOS": ", ".join(member.get("repos") or []) or "workspace",
                  "BRIEF": team + "/knowledge/" + member["knowledge"] if member.get("knowledge") else "none"}
        role = member_id if member_id in ("pm", "tester", "integration-checker") else "engineer"
        out[member_id] = render("codex-" + role + ".md", values) + "\n" + render("codex-common.md", values)
    return out


def bridge(old, roster, previous_hash):
    old = old or ""
    block = (f"{START}\n## Aiset team\n\n"
             f"The {roster['team']} team uses Codex. Read `.claude/team/roster.json` for roles and repository ownership.\n"
             "Shared knowledge, task boards and episodes remain under `.claude/team/`. Do not migrate or duplicate them.\n"
             "For an Aiset PM session, read `.codex/aiset/pm.md`. Use the project's custom Codex agents for delegated work.\n"
             "Keep project instructions outside this managed section unchanged.\n" + END)
    if not old.count(START) and not old.count(END):
        return old + ("\n\n" if old and not old.endswith("\n\n") else "") + block + "\n", digest(block)
    if old.count(START) != 1 or old.count(END) != 1 or old.index(END) < old.index(START):
        raise ValueError("AGENTS.md has malformed Aiset markers; repair them before initializing Codex")
    start, end = old.index(START), old.index(END) + len(END)
    if digest(old[start:end]) != previous_hash:
        return None, previous_hash  # even --force preserves a hand-edited project instruction block
    return old[:start] + block + old[end:], digest(block)


def write_agents(ws, roster, repos, force=False, *, project_guidance=None):
    data = manifest(ws)
    roles = instructions(ws, roster, repos)
    guidance = data.get("projectGuidance", True) if project_guidance is None else project_guidance
    if not isinstance(guidance, bool):
        raise ValueError("invalid Codex projectGuidance preference in generation manifest")
    bridge_hash = data.get("bridgeHash")
    if guidance:
        agents_path = safe_path(ws, "AGENTS.md")
        project = read(agents_path)
        new_project, bridge_hash = bridge(project, roster, bridge_hash)
    outputs = {f".codex/agents/{mid}.toml": agent_toml(m, roles[mid])
               for m in roster["members"] for mid in (m["id"],)}
    outputs[".codex/aiset/pm.md"] = roles["pm"]
    from .codex_hooks import config as hook_config
    outputs[".codex/hooks.json"] = json.dumps(hook_config(ws), indent=2) + "\n"
    # Validate every destination before writing any file, including symlinked directories.
    for relative in outputs:
        safe_path(ws, relative)
    written, kept = [], []
    for relative, text in outputs.items():
        path = safe_path(ws, relative)
        old = read(path)
        owner_hash = data["files"].get(relative)
        if old is not None and digest(old) != owner_hash and not (force and owner_hash):
            kept.append(relative)
            continue
        if old != text:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            write_text_atomic(path, text, newline="")
            written.append(relative)
        data["files"][relative] = digest(text)
    if guidance and new_project is None:
        kept.append("AGENTS.md (edited Aiset section)")
    elif guidance and new_project != project:
        write_text_atomic(agents_path, new_project, newline="")
        written.append("AGENTS.md")
    data.update({"bridgeHash": bridge_hash, "repos": repos, "projectGuidance": guidance})
    path = safe_path(ws, MANIFEST)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    text = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    if read(path) != text:
        write_text_atomic(path, text, newline="")
    return written, kept


def sync(ws, roster):
    data = manifest(ws)
    if "repos" not in data:
        return []
    written, _ = write_agents(ws, roster, data["repos"])
    return written


def agent_files(ws, roster):
    try:
        data = manifest(ws)
    except (OSError, ValueError):
        data = {"files": {}}  # Unknown ownership stays protected, even with a broken manifest.
    out = {}
    for member in roster["members"]:
        relative = f".codex/agents/{member['id']}.toml"
        path = safe_path(ws, relative)
        text = read(path)
        generated = text is not None and digest(text) == data["files"].get(relative)
        out[member["id"]] = {"exists": text is not None, "path": path.replace("\\", "/"),
                             "generated": generated, "model": options(member)[0] if generated else ""}
    return out
