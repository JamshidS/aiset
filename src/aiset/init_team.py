#!/usr/bin/env python3
"""Set up (or update) an AI team inside a folder of repositories.

  python init_team.py <folder>                  scan the repos and write the team into <folder>/.claude
  python init_team.py <folder> --team example-project  name the team (default: the folder name)
  python init_team.py <folder> --force          also overwrite agent files you edited by hand
  python init_team.py <folder> --group stack    one engineer per stack (Java, Node, Python…) instead of per repo;
                                                the default when there are more than 12 repos or services
  python init_team.py <folder> --share          let git see .claude/ (by default a monorepo's .claude/ is
                                                added to .git/info/exclude, so it stays on this machine)
  python init_team.py <folder> --no-launcher    don't write the <team>-pm command

A folder of git repositories gets one unit per repo. A monorepo (the folder is itself a git repo) gets
one unit per top-level folder that has a build file (pom.xml, package.json, requirements.txt, Dockerfile…).

What it writes (see workspace.py for how the office finds it):

  <folder>/.claude/team/roster.json      one engineer per repo, plus PM, QA and integration checker.
                                         Edit names, roles and duties here; an existing roster is
                                         kept, and repos added since are appended to it.
  <folder>/.claude/agents/<id>.md        agent definitions, rendered from templates/ and the roster.
                                         Files that still end with the "generated" marker are
                                         re-rendered on every run; remove the marker to keep your edits.
  <folder>/.claude/team/knowledge/*.md   empty briefs; ask the PM to "build the knowledge briefs".
  <folder>/.claude/team/{tasks,episodes,graph}/
  ~/.aiset/workspaces.json               the team's name and folder (registry.py), so `aiset` finds it
                                         from anywhere and `aiset --workspace <team>` works
  <aiset's scripts dir>/<team>-pm        a command that starts the PM in <folder> from anywhere

Then:  <team>-pm                                  talk to the PM (or: cd <folder> && claude --agent pm)
       aiset --workspace <team>                   watch the office
"""
