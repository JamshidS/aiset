def fwd(p):
    return p.replace("\\", "/")


def _read(path, limit=200000):
    try:
        with open(path, encoding="utf-8-sig", errors="replace") as f:
            return f.read(limit)
    except OSError:
        return ""


def detect(repo_dir):
    """(kind, stack, check commands) from the files at the top of a repo."""
    has = lambda *names: any(os.path.exists(os.path.join(repo_dir, n)) for n in names)
    pkg = _read(os.path.join(repo_dir, "package.json"))
    if pkg:
        try:
            p = json.loads(pkg)
        except ValueError:
            p = {}
        deps = {**p.get("dependencies", {}), **p.get("devDependencies", {})}
        scripts = p.get("scripts", {})
        fw = ("Next.js" if "next" in deps else "React" if "react" in deps else "Vue" if "vue" in deps
              else "Angular" if "@angular/core" in deps else "Svelte" if "svelte" in deps
              else "NestJS" if "@nestjs/core" in deps else "Express" if "express" in deps
              else "Fastify" if "fastify" in deps else "Koa" if "koa" in deps else "Node.js")
        lang = "TypeScript" if "typescript" in deps or has("tsconfig.json") else "JavaScript"
        checks = [f"npm run {s}" for s in ("lint", "test", "build") if s in scripts]
        if lang == "TypeScript":
            checks.insert(1 if checks[:1] == ["npm run lint"] else 0, "npx tsc --noEmit")
        # a Node package without a UI framework is a backend (API, worker, consumer)
        kind = "frontend" if fw in ("Next.js", "React", "Vue", "Angular", "Svelte") else "backend"
        return kind, f"{fw} / {lang}", checks
    py = _read(os.path.join(repo_dir, "requirements.txt")) + _read(os.path.join(repo_dir, "pyproject.toml"))
    if py or has("setup.py", "manage.py"):
        fw = next((n for k, n in (("fastapi", "FastAPI"), ("django", "Django"), ("flask", "Flask"), ("cherrypy", "CherryPy")) if k in py.lower()), "")
        checks = ["pytest"] + (["ruff check ."] if "ruff" in py else []) + (["alembic check"] if has("alembic.ini") else [])
        return "backend", f"{fw + ' / ' if fw else ''}Python", checks
    if has("build.gradle", "build.gradle.kts", "pom.xml"):
        build = _read(os.path.join(repo_dir, "build.gradle")) + _read(os.path.join(repo_dir, "build.gradle.kts")) + _read(os.path.join(repo_dir, "pom.xml"))
        fw = "Spring Boot / " if "spring" in build.lower() else ""
        lang = "Kotlin" if has("build.gradle.kts") or "kotlin" in build.lower() else "Java"
        checks = ["./gradlew test", "./gradlew build -x test"] if has("gradlew") else ["mvn test"]
        return "backend", f"{fw}{lang}", checks
    if has("go.mod"):
        return "backend", "Go", ["go test ./...", "go vet ./..."]
    files = os.listdir(repo_dir)
    if any(re.search(r"(compose.*\.ya?ml|\.tf|nginx.*\.conf|Dockerfile|k8s|helm)", f, re.I) for f in files):
        return "infra", "Docker Compose / deploy config", ["docker compose -f <file> config -q"]
    return "other", "unknown stack", []


def readme_summary(repo_dir):
    """The first sentence-like line of the README, without markdown."""
    fence = False
    for line in _read(os.path.join(repo_dir, "README.md"), 20000).splitlines():
        if line.lstrip().startswith(("```", "~~~")):
            fence = not fence
            continue
        # skip code, setup steps (list items, install hints), link definitions and HTML banners like the NestJS logo
        if fence or line.startswith(("    ", "\t")) or re.match(r"\s*([-*+]|\d+\.)\s|\s*<|\s*\[[^\]]+\]:|\s*\[?!\[", line) \
                or re.search(r"\binstall|\bsource\s", line, re.I):
            continue
        line = re.sub(r"[*_`>#]|!\[.*?\]\(.*?\)|\[(.*?)\]\(.*?\)", r"\1", line).strip()
        if len(line) > 25 and not line.lower().startswith(("git clone", "npm ", "cd ", "http")):
            return line[:160]
    return ""


UNIT_FILES = ("pom.xml", "build.gradle", "build.gradle.kts", "package.json", "requirements.txt", "pyproject.toml",
              "setup.py", "go.mod", "Cargo.toml", "composer.json", "Gemfile", "Dockerfile")


def is_monorepo(ws):
    """The folder is one git repository with its services in subfolders, rather than a folder of repos."""
    return os.path.isdir(os.path.join(ws, ".git")) and not any(
        os.path.isdir(os.path.join(ws, n, ".git")) for n in os.listdir(ws) if not n.startswith("."))


def scan(ws):
    repos = []
    mono = is_monorepo(ws)
    for name in sorted(os.listdir(ws)):
        d = os.path.join(ws, name)
        if name.startswith(".") or not os.path.isdir(d):
            continue
        if mono:
            if name in ("node_modules", "docs") or not any(os.path.exists(os.path.join(d, f)) for f in UNIT_FILES):
                continue
        elif not os.path.isdir(os.path.join(d, ".git")):
            continue
        kind, stack, checks = detect(d)
        if mono:  # commands run from the monorepo root
            checks = [f"cd {name} && {c}" for c in checks]
        repos.append({"name": name, "kind": kind, "stack": stack, "checks": checks, "summary": readme_summary(d)})
    return repos


# --group stack: one engineer per technology family
FAMILIES = [  # (id, role, test: stack -> bool)
    ("frontend", "Frontend Engineer", lambda r: r["kind"] == "frontend"),
    ("devops", "DevOps Engineer", lambda r: r["kind"] == "infra"),
    ("java-backend", "Java Backend Engineer", lambda r: re.search(r"\bJava\b|Kotlin|Spring", r["stack"])),
    ("node-backend", "Node.js Backend Engineer", lambda r: re.search(r"Node|Express|NestJS|Fastify|Koa|JavaScript|TypeScript", r["stack"])),
    ("python-backend", "Python Engineer", lambda r: "Python" in r["stack"]),
    ("go-backend", "Go Engineer", lambda r: "Go" in r["stack"]),
    ("engineer", "Engineer", lambda r: True),
]


def family(repo):
    return next(f for f in FAMILIES if f[2](repo))


def root_files(ws):
    """CI, root build files and folders without a service in a monorepo's root (what DevOps looks after)."""
    out = []
    for n in sorted(os.listdir(ws)):
        p = os.path.join(ws, n)
        if n in (".gitlab-ci.yml", "Jenkinsfile", "pom.xml", "build.gradle", "settings.gradle", "docker-compose.yml", "Makefile") \
                or re.match(r"(docker-)?compose.*\.ya?ml$", n) or (n == ".github" and os.path.isdir(p)):
            out.append(n)
        elif os.path.isdir(p) and not n.startswith(".") and n not in ("node_modules", "docs") \
                and not any(os.path.exists(os.path.join(p, f)) for f in UNIT_FILES) and re.search(r"infra|deploy|k8s|helm|terraform|ops|ci", n, re.I):
            out.append(n + "/")
    return out


def stack_engineers(repos, start=0):
    groups = {}
    for r in repos:
        groups.setdefault(family(r)[0], []).append(r)
    out = []
    for i, (fid, role, _) in enumerate(f for f in FAMILIES if f[0] in groups):
        own = groups[fid]
        stacks = sorted({r["stack"] for r in own}, key=lambda st: -sum(1 for r in own if r["stack"] == st))
        n = len(own)
        out.append({"id": fid, "name": NAMES[(start + i) % len(NAMES)], "role": role,
                    "zone": "infra" if fid == "devops" else "eng", "color": "#f97316" if fid == "devops" else COLORS[(start + i) % len(COLORS)],
                    "knowledge": fid + ".md", "repos": [r["name"] for r in own], "stack": ", ".join(stacks[:3]),
                    "checks": [], "duty": f"{n} service{'s' if n > 1 else ''} ({', '.join(stacks[:2])}): " + ", ".join(r["name"] for r in own)})
    return out


ROLE = {"backend": ("Backend Engineer", "eng"), "frontend": ("Frontend Engineer", "eng"),
        "infra": ("DevOps Engineer", "infra"), "other": ("Engineer", "eng")}


def engineer(repo, name, color):
    role, zone = ROLE[repo["kind"]]
    duty = f"{repo['name']} · {repo['stack']}" + (f" · {repo['summary']}" if repo["summary"] else "")
    return {"id": repo["name"], "name": name, "role": role, "zone": zone, "color": color,
            "knowledge": repo["name"] + ".md", "repos": [repo["name"]], "stack": repo["stack"],
            "checks": repo["checks"], "duty": duty}


def build_roster(ws, team, repos, old, group="repo"):
    """A new roster, or the old one with engineers for repos it doesn't cover yet."""
    if old and group == "stack":
        roster, added = old, []
        for r in repos:
            if any(r["name"] in (m.get("repos") or []) for m in roster["members"]):
                continue
            owner = next((m for m in roster["members"] if m["id"] == family(r)[0]), None)
            if owner:
                owner["repos"].append(r["name"])
                added.append(r["name"])
        if team:
            roster["team"] = team
        return roster, added
    if old:
        roster = old
        owned = {r for m in roster["members"] for r in m.get("repos") or []}
        taken = {m["name"] for m in roster["members"]}
        free = [n for n in NAMES if n not in taken]
        added = []
        for i, repo in enumerate(r for r in repos if r["name"] not in owned):
            m = engineer(repo, free[i % len(free)] if free else repo["name"], COLORS[(len(roster["members"]) + i) % len(COLORS)])
            # engineers go before QA so the office keeps its order
            at = next((k for k, x in enumerate(roster["members"]) if x["zone"] in ("qa", "infra") and m["zone"] == "eng"), len(roster["members"]))
            roster["members"].insert(at, m)
            added.append(repo["name"])
        if team:
            roster["team"] = team
        return roster, added
    members = [{"id": "pm", "name": "Patron", "role": "Project Manager", "zone": "pm", "color": "#ec4899",
                "knowledge": None, "duty": "Your point of contact. Clarifies, plans, assigns, validates."}]
    order = sorted(repos, key=lambda r: ["backend", "frontend", "other", "infra"].index(r["kind"]))
    if group == "stack":
        engs = stack_engineers(order)
        root = root_files(ws) if is_monorepo(ws) else []
        if root:  # a monorepo's CI, root build and infra folders belong to DevOps
            dev = next((m for m in engs if m["id"] == "devops"), None)
            if not dev:
                dev = {"id": "devops", "name": NAMES[len(engs) % len(NAMES)], "role": "DevOps Engineer", "zone": "infra", "color": "#f97316",
                       "knowledge": "devops.md", "repos": [], "stack": "CI / Docker", "checks": [], "duty": ""}
                engs.append(dev)
            dev["duty"] = "The monorepo root: " + ", ".join(root) + (f"; and {dev['duty']}" if dev["duty"] else "")
        members += [m for m in engs if m["zone"] != "infra"]
        members += [
            {"id": "tester", "name": "Derya", "role": "QA Engineer", "zone": "qa", "color": "#eab308", "knowledge": None,
             "duty": "Runs tests, lint & type-checks; writes tests"},
            {"id": "integration-checker", "name": "Kerem", "role": "Integration Checker", "zone": "qa", "color": "#ef4444",
             "knowledge": "integration-checker.md", "duty": "Cross-service contracts, auth, env & deploy wiring"},
        ]
        members += [m for m in engs if m["zone"] == "infra"]
        name = team or os.path.basename(os.path.abspath(ws))
        return {"team": name, "pmCommand": "claude --agent pm", "group": "stack", "members": members}, [r["name"] for r in repos]
    for i, repo in enumerate(order):
        if repo["kind"] != "infra":
            members.append(engineer(repo, NAMES[i % len(NAMES)], COLORS[i % len(COLORS)]))
    members += [
        {"id": "tester", "name": "Derya", "role": "QA Engineer", "zone": "qa", "color": "#eab308", "knowledge": None,
         "duty": "Runs tests, lint & type-checks; writes tests"},
        {"id": "integration-checker", "name": "Kerem", "role": "Integration Checker", "zone": "qa", "color": "#ef4444",
         "knowledge": "integration-checker.md", "duty": "Cross-repo contracts, auth, env & compose wiring"},
    ]
    for i, repo in enumerate(r for r in order if r["kind"] == "infra"):
        members.append(engineer(repo, NAMES[(len(members) + i) % len(NAMES)], "#f97316"))
    name = team or os.path.basename(os.path.abspath(ws))
    return {"team": name, "pmCommand": "claude --agent pm", "members": members}, [r["name"] for r in repos]


def render(template, values):
    with open(os.path.join(TEMPLATES, template), encoding="utf-8") as f:
        text = f.read()
    for k, v in values.items():
        text = text.replace("{{" + k + "}}", str(v))
    missing = sorted(set(re.findall(r"\{\{(\w+)\}\}", text)))
    if missing:
        raise SystemExit(f"{template}: no value for {', '.join(missing)}")
    return text.rstrip() + "\n\n" + MARKER + "\n"


def helpers_section(helpers):
    """The PM's note on the built-in helper agents, from roster.json "helpers" (optional)."""
    if not helpers or not helpers.get("agents"):
        return ""
    rows = "\n".join(f"| `{t}` | {a[0]} · {a[1]} |" for t, a in helpers["agents"].items())
    return (f"\n### {helpers.get('label', 'Helpers')}\n\n"
            "Built-in helper agents (no repo, no brief). Use them for small jobs that don't need an owner: "
            "finding where something lives across repos, reading logs or data files, mechanical edits, drafting a plan. "
            "Give them `model: haiku` unless the job is hard. Anything that changes a repo still goes to its owner for review.\n\n"
            "| `subagent_type` | Name · role |\n|---|---|\n" + rows + "\n")


def write_agents(ws, roster, repos, force):
    from .sync_names import set_model, set_pinned
    team_dir = fwd(os.path.join(os.path.abspath(ws), ".claude", "team"))
    agents_dir = os.path.join(ws, ".claude", "agents")
    os.makedirs(agents_dir, exist_ok=True)
    by_name = {r["name"]: r for r in repos}
    members = roster["members"]
    py = "python" if shutil.which("python") else "python3"
    base = {
        "TEAM_NAME": roster["team"], "WS": fwd(os.path.abspath(ws)),
        "KNOWLEDGE": team_dir + "/knowledge", "BOARDS": team_dir + "/tasks", "EPISODES": team_dir + "/episodes",
        "TEAMMAP": f'{py} "{fwd(os.path.join(HERE, "teammap.py"))}"',
        "REPO_LIST": "\n".join(f"- `{r['name']}` ({r['stack']})" + (f": {r['summary']}" if r["summary"] else "") for r in repos),
        "TEAM_TABLE": "\n".join(f"| `{m['id']}` | {m['name']} · {m['role']} | {', '.join(m.get('repos') or []) or m.get('duty', '')} |"
                                for m in members if m["id"] != "pm"),
        "HELPERS": helpers_section(roster.get("helpers")),
        "TEST_TABLE": "\n".join(f"- `{r['name']}` ({r['stack']}): " + (", ".join(f"`{c}`" for c in r["checks"]) or "no standard checks found")
                                for r in repos),
    }
    written, kept = [], []
    for m in members:
        own = [by_name[r] for r in m.get("repos") or [] if r in by_name]
        checks = []
        for r in own:  # in a monorepo every service has the same commands; show the pattern once
            for c in r["checks"]:
                c = c.replace(r["name"], "<service>") if len(own) > 1 else c
                if c not in checks:
                    checks.append(c)
        values = {**base, "ID": m["id"], "NAME": m["name"], "ROLE": m["role"], "DUTY": m.get("duty", ""),
                  "REPOS": ", ".join(m.get("repos") or []) or "-",
                  "STACK": ", ".join(r["stack"] for r in own) or m.get("stack", ""),
                  "TEST_HINTS": f" Here: {', '.join(f'`{c}`' for c in checks)}." if checks else ""}
        if own:
            values["REPO_LIST"] = "\n".join(f"- `{r['name']}` at `{base['WS']}/{r['name']}` ({r['stack']})" for r in own)
        template = {"pm": "pm.md", "tester": "tester.md", "integration-checker": "integration-checker.md"}.get(m["id"], "engineer.md")
        path = os.path.join(agents_dir, m["id"] + ".md")
        old = _read(path)
        if old and not any(mk in old for mk in (MARKER, *OLD_MARKERS)) and not force:
            kept.append(m["id"])
            continue
        new = set_model(render(template, values), m.get("model"))  # the model chosen in Settings
        if m["id"] == "pm":
            new = set_pinned(new, roster)
        if new != old:
            write_text_atomic(path, new, newline="\n")
            written.append(m["id"])
    return written, kept


def write_briefs(ws, roster):
    kdir = os.path.join(ws, ".claude", "team", "knowledge")
    made = []
    for m in roster["members"]:
        if not m.get("knowledge"):
            continue
        path = os.path.join(kdir, m["knowledge"])
        if os.path.exists(path):
            continue
        what = ", ".join(m.get("repos") or []) or m.get("duty", "")
        text = (f"# {m['name']} · {what}\n> STATUS: stub. Ask the PM to \"build the knowledge briefs\" to fill this in.\n\n"
                f"## Field notes\n")
        write_text_atomic(path, text, newline="\n")
        made.append(m["knowledge"])
    return made


def main():
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")  # Windows consoles default to cp1252
    ap = argparse.ArgumentParser(description="Set up an AI team inside a folder of repositories.")
    from . import __version__
    ap.add_argument("--version", action="version", version="aiset-init " + __version__)
    ap.add_argument("folder")
    ap.add_argument("--team", help="team name shown in the office (default: folder name)")
    ap.add_argument("--force", action="store_true", help="overwrite agent files even if you edited them")
    ap.add_argument("--group", choices=("repo", "stack"), help="one engineer per repo, or per stack (default: stack above 12 units)")
    ap.add_argument("--share", action="store_true", help="don't hide .claude/ from git in a monorepo")
    ap.add_argument("--no-launcher", action="store_true", help="don't write the <team>-pm command")
    args = ap.parse_args()
    ws = os.path.abspath(args.folder)
    repos = scan(ws)
    if not repos:
        raise SystemExit(f"no git repositories (or, in a monorepo, service folders) under {ws}")
    team_dir = os.path.join(ws, ".claude", "team")
    for sub in ("knowledge", "tasks", "episodes", "graph"):
        os.makedirs(os.path.join(team_dir, sub), exist_ok=True)
    roster_path = os.path.join(team_dir, "roster.json")
    old = None
    if os.path.exists(roster_path):
        with open(roster_path, encoding="utf-8-sig") as f:
            old = json.load(f)
    group = args.group or (old or {}).get("group") or ("stack" if len(repos) > 12 else "repo")
    old_team = (old or {}).get("team")  # build_roster renames the old roster in place
    roster, added = build_roster(ws, args.team, repos, old, group)
    hidden = False
    if is_monorepo(ws) and not args.share:  # keep the team out of the project's git
        exclude = os.path.join(ws, ".git", "info", "exclude")
        os.makedirs(os.path.dirname(exclude), exist_ok=True)
        if "/.claude/" not in _read(exclude).split():
            with open(exclude, "a", encoding="utf-8") as f:
                f.write("\n# aiset team (init_team.py)\n/.claude/\n")
        hidden = True
    write_text_atomic(roster_path, json.dumps(roster, indent=2, ensure_ascii=False) + "\n", newline="\n")
    written, kept = write_agents(ws, roster, repos, args.force)
    briefs = write_briefs(ws, roster)
    registry.register(roster["team"], ws)
    launcher, bin_dir, on_path = None, None, False
    if not args.no_launcher:
        bin_dir, on_path = registry.scripts_dir()
        launcher = registry.write_launcher(roster["team"], ws, bin_dir)

    print(f"Team '{roster['team']}' in {ws}" + (f"  (monorepo, {len(repos)} services, one engineer per {group})" if is_monorepo(ws) else ""))
    for r in repos:
        owner = next((m["name"] for m in roster["members"] if r["name"] in (m.get("repos") or [])), "-")
        print(f"  {r['name']:30} {r['stack']:32} → {owner}")
    print(f"roster:  {roster_path}" + (f"  (added: {', '.join(added)})" if added and old else ""))
    print(f"agents:  {', '.join(written) or 'up to date'}" + (f"  (kept your edits: {', '.join(kept)})" if kept else ""))
    if briefs:
        print(f"briefs:  {', '.join(briefs)} (stubs)")
    if hidden:
        print("git:     .claude/ is in .git/info/exclude (local only; use --share to let git see it)")
    name, pm_cmd = registry.slug(roster["team"]) + "-pm", None
    if launcher:
        print(f"command: {name} starts the PM from any folder ({launcher})")
        if on_path:
            pm_cmd = name
            ours = {"claude --agent pm"}  # values we wrote; one edited in Settings stays
            if old_team:
                ours.add(registry.slug(old_team) + "-pm")  # the launcher name before a team rename
            current = roster.get("pmCommand", "claude --agent pm")
            if current in ours and current != name:
                roster["pmCommand"] = name
                write_text_atomic(roster_path, json.dumps(roster, indent=2, ensure_ascii=False) + "\n", newline="\n")
        else:
            print(f"         {bin_dir} is not on PATH yet: add it, or run the file by its full path")
    elif not args.no_launcher:
        print(f"command: not written: {name} already exists in {bin_dir} and wasn't made by aiset-init")
