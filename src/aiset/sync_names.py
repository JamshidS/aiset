#!/usr/bin/env python3
"""Copy the names and models in roster.json into the agent definitions (<agents>/*.md, see workspace.py).

roster.json is the single place to rename team members and pick their models (the Settings page
edits it too). The office server runs this automatically whenever roster.json changes; you can
also run it by hand. Rewritten:
  - the name, in the description line, the "You are **Name, the Role**" line and the PM's team table;
  - the model: the `model:` line of each agent's frontmatter (removed when the member has none),
    and the PM's "Pinned models" section, so the PM doesn't override them per assignment.
"""
import os
import re
import sys

if __name__ == "__main__" and not __package__:  # run as a file: python src/aiset/sync_names.py
    sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.realpath(__file__))))
    __package__ = "aiset"
from .workspace import AGENTS, load_roster  # noqa: E402
from .atomic import write_text_atomic  # noqa: E402

PINNED_START, PINNED_END = "<!-- pinned models: written by aiset settings -->", "<!-- /pinned models -->"


def set_model(text, model):
    """text with its frontmatter `model:` line set to model, or removed when model is empty."""
    m = re.match(r"^---\r?\n(.*?\r?\n)---\r?\n", text, re.S)
    if not m:
        return text
    front = re.sub(r"^model:.*\r?\n", "", m.group(1), flags=re.M)
    if model:
        line = f"model: {model}\n"
        tools = re.search(r"^tools:.*\n", front, re.M)
        front = front[:tools.end()] + line + front[tools.end():] if tools else front + line
    return "---\n" + front + "---\n" + text[m.end():]


def pinned_section(roster):
    pinned = [(m["id"], m["name"], m["model"]) for m in roster["members"] if m.get("model") and m["id"] != "pm"]
    if not pinned:
        return ""
    rows = "\n".join(f"- `{i}` ({n}): `{mdl}`" for i, n, mdl in pinned)
    return (f"{PINNED_START}\n## Pinned models\n\nThe user chose these models in the office settings. "
            f"Don't pass `model` when you assign work to these agents; their own model applies:\n\n{rows}\n{PINNED_END}\n")


def set_pinned(text, roster):
    text = re.sub(r"\n*" + re.escape(PINNED_START) + r".*?" + re.escape(PINNED_END) + r"\n?", "\n", text, flags=re.S)
    section = pinned_section(roster)
    if not section:
        return text
    # before the generated-file marker when there is one, so init_team still recognises the file
    marker = re.search(r"^<!-- generated by .*-->\s*$", text, re.M)
    at = marker.start() if marker else len(text)
    return text[:at].rstrip() + "\n\n" + section + ("\n" + text[at:] if marker else "")


def sync(roster):
    from . import providers, workspace
    if providers.name(roster) == "codex":
        from .providers.codex import sync as sync_codex
        return sync_codex(workspace.WORKSPACE, roster)
    changed = []
    for m in roster["members"]:
        path = os.path.join(AGENTS, m["id"] + ".md")
        if not os.path.exists(path):
            continue
        with open(path, encoding="utf-8", errors="surrogateescape") as f:
            text = f.read()
        new = re.sub(r'^(description: ")[^"·]+?( · )', lambda x: x.group(1) + m["name"] + x.group(2), text, count=1, flags=re.M)
        new = re.sub(r"(You are \*\*).+?(, the )", lambda x: x.group(1) + m["name"] + x.group(2), new, count=1)
        new = set_model(new, m.get("model"))
        if new != text:
            write_text_atomic(path, new, errors="surrogateescape", newline="\n")
            changed.append(m["id"])
    pm = os.path.join(AGENTS, "pm.md")
    if os.path.exists(pm):
        with open(pm, encoding="utf-8", errors="surrogateescape") as f:
            text = f.read()
        new = text
        for m in roster["members"]:
            new = re.sub(r"^(\| `%s` \| ).+?( · )" % re.escape(m["id"]),
                         lambda x: x.group(1) + m["name"] + x.group(2), new, count=1, flags=re.M)
        new = set_pinned(new, roster)
        if new != text:
            write_text_atomic(pm, new, errors="surrogateescape", newline="\n")
            changed.append("pm table")
    return changed


if __name__ == "__main__":
    print("updated:", ", ".join(sync(load_roster())) or "nothing (already in sync)")
